/**
 * Generates the SQLite mirror of the canonical PostgreSQL schema.
 *
 * The canonical `prisma/schema.prisma` targets PostgreSQL (production).
 * This script emits `prisma/schema.sqlite.prisma` — byte-identical except for the
 * datasource provider — enabling zero-config local development/testing without
 * Docker or a PostgreSQL server. Models, relations and code are unchanged.
 *
 * Usage: npm run setup:local
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "prisma", "schema.prisma");
const target = join(root, "prisma", "schema.sqlite.prisma");

const original = readFileSync(source, "utf8");

// Anchor to the datasource block so comment text is never rewritten.
const datasourcePattern = /(datasource\s+db\s*\{[\s\S]*?)provider\s*=\s*"postgresql"/;
if (!datasourcePattern.test(original)) {
  console.error("[make-sqlite-schema] Could not find the PostgreSQL datasource provider in prisma/schema.prisma");
  process.exit(1);
}

const banner = `// AUTO-GENERATED FILE — do not edit by hand.
// Source: prisma/schema.prisma (PostgreSQL). Generated by scripts/make-sqlite-schema.mjs.
// Only the datasource provider differs; all models/relations/fields are identical.
`;

const output = banner + original.replace(datasourcePattern, '$1provider = "sqlite"');

writeFileSync(target, output, "utf8");
console.log(`[make-sqlite-schema] Wrote ${target} (provider = sqlite)`);
