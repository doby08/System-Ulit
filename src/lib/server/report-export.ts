/**
 * Server-side report exporters.
 *
 * Turns a persisted `ReportContent` payload into a downloadable file. Every exporter is
 * dependency-light and runs inside the Next.js node runtime:
 *   - PDF   → jsPDF (text layout with page breaks)
 *   - Word  → docx   (.docx)
 *   - Excel → exceljs (.xlsx, several sheets)
 *   - CSV / JSON → plain text
 */
import { jsPDF } from "jspdf";
import { Document, HeadingLevel, Packer, Paragraph, Table, TableCell, TableRow, TextRun, WidthType } from "docx";
import ExcelJS from "exceljs";
import type { ReportContent } from "@/lib/types-analytics";

export type ReportFormat = "pdf" | "word" | "excel" | "csv" | "json";

export const REPORT_FORMATS: ReportFormat[] = ["pdf", "word", "excel", "csv", "json"];

export function isReportFormat(value: string): value is ReportFormat {
  return (REPORT_FORMATS as string[]).includes(value);
}

export const REPORT_MIME: Record<ReportFormat, string> = {
  pdf: "application/pdf",
  word: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  excel: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  csv: "text/csv; charset=utf-8",
  json: "application/json; charset=utf-8",
};

export const REPORT_EXTENSION: Record<ReportFormat, string> = {
  pdf: "pdf",
  word: "docx",
  excel: "xlsx",
  csv: "csv",
  json: "json",
};

function formatWhen(iso: string) {
  try {
    return new Date(iso).toLocaleString("en-PH", { dateStyle: "medium", timeStyle: "short" });
  } catch {
    return iso;
  }
}

function safeName(value: string) {
  return (
    (value || "report")
      .replace(/[^a-z0-9._-]+/gi, "-")
      .replace(/-+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 80) || "report"
  );
}

export function reportFileName(content: ReportContent, format: ReportFormat) {
  const reportId = content.reportId ? `-${content.reportId.slice(0, 8)}` : "";
  return `${safeName(`${content.reportType}-report-${content.survey.title}`)}${reportId}.${REPORT_EXTENSION[format]}`;
}

/** Flat key/value overview lines reused by every exporter. */
function overviewLines(content: ReportContent) {
  const o = content.overview;
  return [
    { label: "Survey", value: content.survey.title },
    { label: "Topic", value: content.survey.topic },
    { label: "Stakeholder", value: content.survey.stakeholder },
    { label: "Interview method", value: content.survey.interviewMethod },
    { label: "Interview mode", value: content.survey.interviewMode },
    { label: "Language", value: content.survey.language },
    { label: "Survey version", value: `v${content.survey.version} (${content.survey.status})` },
    { label: "Total responses", value: String(o.totalResponses) },
    { label: "Completed interviews", value: String(o.completedInterviews) },
    { label: "Completion rate", value: `${o.completionRate}%` },
    { label: "Average Likert score", value: String(o.averageLikertScore) },
    { label: "Satisfaction", value: `${o.averageSatisfactionPercent}%` },
    { label: "Respondents", value: String(o.totalRespondents) },
    { label: "Average duration", value: `${o.averageDurationSec}s` },
    { label: "Offline pending sync", value: String(o.offlinePending) },
    { label: "Generated at", value: formatWhen(content.generatedAt) },
    { label: "Generated by", value: content.generatedBy },
    { label: "AI engine", value: content.aiProvider },
  ];
}


