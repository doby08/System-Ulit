function docxHeading(value: string) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 120 }, children: [new TextRun(value)] });
}

function docxBullet(value: string) {
  return new Paragraph({ bullet: { level: 0 }, spacing: { after: 60 }, children: [new TextRun(value)] });
}

function docxTable(headers: string[], rows: string[][]) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map(
          (header) =>
            new TableCell({
              shading: { fill: "EEF2FF" },
              children: [new Paragraph({ children: [new TextRun({ text: header, bold: true, size: 20 })] })],
            }),
        ),
      }),
      ...rows.map(
        (row) =>
          new TableRow({
            children: row.map(
              (cell) => new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: cell, size: 20 })] })] }),
            ),
          }),
      ),
    ],
  });
}

export async function buildReportDocx(content: ReportContent): Promise<Buffer> {
  const children: (Paragraph | Table)[] = [
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun(content.title)] }),
    new Paragraph({ children: [new TextRun({ text: `${content.survey.topic} · ${content.survey.stakeholder}`, size: 22 })] }),
    new Paragraph({
      children: [
        new TextRun({
          text: `Generated ${formatWhen(content.generatedAt)} by ${content.generatedBy} · AI engine: ${content.aiProvider}`,
          size: 18,
          color: "64748B",
        }),
      ],
    }),
  ];

  children.push(docxHeading("Executive summary"));
  children.push(new Paragraph({ children: [new TextRun(content.aiSummary)] }));

  children.push(docxHeading("Key metrics"));
  children.push(docxTable(["Field", "Value"], overviewLines(content).map((l) => [l.label, l.value])));

  if (content.sentiment.length) {
    children.push(docxHeading("Sentiment distribution"));
    children.push(docxTable(["Label", "Count", "Percentage"], content.sentiment.map((s) => [s.label, String(s.value), `${s.percentage}%`])));
  }

  if (content.trend.length) {
    children.push(docxHeading("Response trend"));
    children.push(docxTable(["Date", "Responses", "Completed"], content.trend.map((t) => [t.date, String(t.responses), String(t.completed)])));
  }

  if (content.demographics.length) {
    children.push(docxHeading("Respondent groups"));
    children.push(docxTable(["Group", "Responses", "Percentage"], content.demographics.map((g) => [g.label, String(g.value), `${g.percentage}%`])));
  }

  children.push(docxHeading("Question analysis"));
  children.push(
    docxTable(
      ["Code", "Question", "Type", "Answered", "Answer rate", "Likert average"],
      content.questions.map((q) => [
        q.code,
        q.text,
        q.type,
        String(q.answered),
        `${q.answerRate}%`,
        q.likertAverage === null || q.likertAverage === undefined ? "—" : String(q.likertAverage),
      ]),
    ),
  );

  const textQuestions = content.questions.filter((q) => (q.sampleAnswers ?? []).length || q.likertInterpretation);
  if (textQuestions.length) {
    children.push(docxHeading("Question detail"));
    for (const question of textQuestions) {
      children.push(new Paragraph({ spacing: { before: 120 }, children: [new TextRun({ text: `${question.code}. ${question.text}`, bold: true })] }));
      if (question.likertInterpretation) children.push(docxBullet(`Interpretation: ${question.likertInterpretation}`));
      for (const entry of question.distribution ?? []) children.push(docxBullet(`${entry.label}: ${entry.value} (${entry.percentage}%)`));
      for (const sample of question.sampleAnswers ?? []) children.push(docxBullet(`“${sample}”`));
    }
  }

  if (content.keywords.length) {
    children.push(docxHeading("Keywords"));
    children.push(new Paragraph({ children: [new TextRun(content.keywords.map((k) => `${k.keyword} (${k.count})`).join(", "))] }));
  }
  if (content.themes.length) {
    children.push(docxHeading("Themes"));
    for (const theme of content.themes) children.push(docxBullet(`${theme.theme} — ${theme.count} mentions`));
  }
  for (const [title, items] of [
    ["Pain points", content.painPoints],
    ["Suggestions", content.suggestions],
    ["Concerns", content.concerns],
  ] as [string, string[]][]) {
    if (!items.length) continue;
    children.push(docxHeading(title));
    for (const item of items) children.push(docxBullet(item));
  }

  if (content.rawResponses.length) {
    children.push(docxHeading(content.reportType === "SUMMARY" ? "Sample responses" : "Raw responses"));
    children.push(
      docxTable(
        ["Respondent", "Group", "Submitted", "Source", "Question", "Answer"],
        content.rawResponses.flatMap((response) =>
          response.answers.map((answer) => [
            response.respondent,
            response.group ?? "—",
            formatWhen(response.submittedAt),
            response.source,
            `${answer.code} ${answer.question}`,
            answer.answer,
          ]),
        ),
      ),
    );
  }

  const document = new Document({ sections: [{ children }] });
  return Packer.toBuffer(document);
}

