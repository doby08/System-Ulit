/** Builds the requested export, returning the binary payload and its file name. */
export async function buildReportFile(
  content: ReportContent,
  format: ReportFormat,
): Promise<{ body: Buffer; fileName: string; contentType: string }> {
  let body: Buffer;
  switch (format) {
    case "pdf":
      body = buildReportPdf(content);
      break;
    case "word":
      body = await buildReportDocx(content);
      break;
    case "excel":
      body = await buildReportExcel(content);
      break;
    case "json":
      body = Buffer.from(buildReportJson(content), "utf8");
      break;
    case "csv":
    default:
      body = Buffer.from(buildReportCsv(content), "utf8");
      break;
  }
  return { body, fileName: reportFileName(content, format), contentType: REPORT_MIME[format] };
}


