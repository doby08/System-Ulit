function csvCell(value: unknown) {
  const text = value === null || value === undefined ? "" : String(value);
  return `"${text.replace(/"/g, '""').replace(/\r?\n/g, " ")}"`;
}

export function buildReportCsv(content: ReportContent): string {
  const rows: string[] = [];
  rows.push(csvCell(`${content.reportType} REPORT — ${content.survey.title}`));
  rows.push("");
  rows.push([csvCell("Field"), csvCell("Value")].join(","));
  for (const line of overviewLines(content)) rows.push([csvCell(line.label), csvCell(line.value)].join(","));

  rows.push("");
  rows.push(csvCell("Sentiment distribution"));
  rows.push([csvCell("Label"), csvCell("Count"), csvCell("Percentage")].join(","));
  for (const entry of content.sentiment) rows.push([csvCell(entry.label), csvCell(entry.value), csvCell(`${entry.percentage}%`)].join(","));

  rows.push("");
  rows.push(csvCell("Response trend"));
  rows.push([csvCell("Date"), csvCell("Responses"), csvCell("Completed")].join(","));
  for (const point of content.trend) rows.push([csvCell(point.date), csvCell(point.responses), csvCell(point.completed)].join(","));

  rows.push("");
  rows.push(csvCell("Question analytics"));
  rows.push(
    [
      csvCell("Code"),
      csvCell("Question"),
      csvCell("Type"),
      csvCell("Category"),
      csvCell("Answered"),
      csvCell("Answer rate %"),
      csvCell("Likert average"),
      csvCell("Interpretation"),
    ].join(","),
  );
  for (const question of content.questions) {
    rows.push(
      [
        csvCell(question.code),
        csvCell(question.text),
        csvCell(question.type),
        csvCell(question.category ?? ""),
        csvCell(question.answered),
        csvCell(question.answerRate),
        csvCell(question.likertAverage ?? ""),
        csvCell(question.likertInterpretation ?? ""),
      ].join(","),
    );
  }

  if (content.rawResponses.length) {
    rows.push("");
    rows.push(csvCell(content.reportType === "SUMMARY" ? "Sample responses" : "Raw responses"));
    rows.push(
      [
        csvCell("Response"),
        csvCell("Respondent"),
        csvCell("Group"),
        csvCell("Submitted"),
        csvCell("Source"),
        csvCell("Status"),
        csvCell("Question"),
        csvCell("Answer"),
      ].join(","),
    );
    for (const response of content.rawResponses) {
      for (const answer of response.answers) {
        rows.push(
          [
            csvCell(response.responseId.slice(0, 8)),
            csvCell(response.respondent),
            csvCell(response.group ?? ""),
            csvCell(formatWhen(response.submittedAt)),
            csvCell(response.source),
            csvCell(response.status),
            csvCell(`${answer.code} ${answer.question}`),
            csvCell(answer.answer),
          ].join(","),
        );
      }
    }
  }

  rows.push("");
  rows.push(csvCell("AI summary"));
  rows.push(csvCell(content.aiSummary));
  return rows.join("\r\n");
}

export function buildReportJson(content: ReportContent): string {
  return JSON.stringify(content, null, 2);
}

