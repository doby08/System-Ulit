export function buildReportPdf(content: ReportContent): Buffer {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 42;
  const maxWidth = pageWidth - margin * 2;
  let y = margin;

  const ensure = (height: number) => {
    if (y + height > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }
  };
  const line = (value: string, size = 10, style: "normal" | "bold" = "normal", indent = 0) => {
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    const lines = doc.splitTextToSize(value ?? "", maxWidth - indent) as string[];
    for (const piece of lines) {
      ensure(size + 6);
      doc.text(piece, margin + indent, y);
      y += size + 4;
    }
  };
  const gap = (size = 8) => {
    y += size;
  };
  const heading = (value: string) => {
    ensure(40);
    gap(8);
    doc.setFillColor(59, 107, 246);
    doc.rect(margin, y - 11, 3, 13, "F");
    line(value, 13, "bold", 10);
    gap(2);
  };

  line(content.title, 18, "bold");
  line(`${content.survey.topic} · ${content.survey.stakeholder}`, 10);
  line(
    `Generated ${formatWhen(content.generatedAt)} by ${content.generatedBy} · AI engine: ${content.aiProvider}`,
    9,
  );
  gap(4);
  doc.setDrawColor(220, 226, 240);
  doc.line(margin, y, pageWidth - margin, y);

  heading("Executive summary");
  line(content.aiSummary, 10);

  heading("Key metrics");
  for (const item of overviewLines(content)) line(`${item.label}: ${item.value}`, 10);

  if (content.trend.length) {
    heading("Response trend");
    for (const point of content.trend) line(`${point.date} — responses: ${point.responses}, completed: ${point.completed}`, 9);
  }

  if (content.sentiment.length) {
    heading("Sentiment distribution");
    for (const entry of content.sentiment) line(`${entry.label}: ${entry.value} (${entry.percentage}%)`, 10);
  }

  if (content.demographics.length) {
    heading("Respondent groups");
    for (const entry of content.demographics) line(`${entry.label}: ${entry.value} (${entry.percentage}%)`, 10);
  }

  heading("Question analysis");
  for (const question of content.questions) {
    line(`${question.code}. ${question.text}`, 10, "bold");
    const bits = [
      `Type: ${question.type}`,
      question.category ? `Category: ${question.category}` : "",
      `Answered: ${question.answered} (${question.answerRate}%)`,
      question.likertAverage !== null && question.likertAverage !== undefined ? `Likert average: ${question.likertAverage}` : "",
      question.likertInterpretation ?? "",
      question.numericAverage !== null && question.numericAverage !== undefined ? `Average: ${question.numericAverage}` : "",
    ].filter(Boolean);
    line(bits.join(" · "), 9);
    for (const entry of question.distribution ?? []) line(`${entry.label}: ${entry.value} (${entry.percentage}%)`, 9, "normal", 10);
    for (const sample of question.sampleAnswers ?? []) line(`• ${sample}`, 9, "normal", 10);
    gap(3);
  }

  if (content.keywords.length) {
    heading("Keywords");
    line(content.keywords.map((k) => `${k.keyword} (${k.count})`).join(", "), 10);
  }
  if (content.themes.length) {
    heading("Themes");
    for (const theme of content.themes) line(`• ${theme.theme} — ${theme.count} mentions`, 10);
  }
  if (content.painPoints.length) {
    heading("Pain points");
    for (const item of content.painPoints) line(`• ${item}`, 10);
  }
  if (content.suggestions.length) {
    heading("Suggestions");
    for (const item of content.suggestions) line(`• ${item}`, 10);
  }
  if (content.concerns.length) {
    heading("Concerns");
    for (const item of content.concerns) line(`• ${item}`, 10);
  }

  if (content.rawResponses.length) {
    heading(content.reportType === "SUMMARY" ? "Sample responses" : "Raw responses");
    for (const response of content.rawResponses) {
      line(`${response.respondent}${response.group ? ` (${response.group})` : ""} — ${formatWhen(response.submittedAt)} · ${response.source} · ${response.status}`, 9, "bold");
      for (const answer of response.answers) line(`${answer.code}: ${answer.answer}`, 9, "normal", 10);
      gap(3);
    }
  }

  const pageCount = doc.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(120);
    doc.text(`WPU AI Interview & Survey · ${content.survey.title}`, margin, pageHeight - 20);
    doc.text(`Page ${page} of ${pageCount}`, pageWidth - margin, pageHeight - 20, { align: "right" });
    doc.setTextColor(0);
  }

  return Buffer.from(doc.output("arraybuffer"));
}


