function styleHeader(row: ExcelJS.Row) {
  row.font = { bold: true, color: { argb: "FF1E3A8A" } };
  row.eachCell((cell) => {
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE0E7FF" } };
    cell.border = { bottom: { style: "thin", color: { argb: "FF94A3B8" } } };
  });
}

export async function buildReportExcel(content: ReportContent): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "WPU AI Interview & Survey System";
  workbook.created = new Date(content.generatedAt);

  const overview = workbook.addWorksheet("Overview");
  overview.columns = [
    { header: "Field", key: "label", width: 30 },
    { header: "Value", key: "value", width: 60 },
  ];
  styleHeader(overview.getRow(1));
  overview.addRow({ label: "Report", value: content.title });
  for (const item of overviewLines(content)) overview.addRow({ label: item.label, value: item.value });
  overview.addRow({ label: "AI summary", value: content.aiSummary });

  const questions = workbook.addWorksheet("Questions");
  questions.columns = [
    { header: "Code", key: "code", width: 10 },
    { header: "Question", key: "text", width: 60 },
    { header: "Type", key: "type", width: 16 },
    { header: "Category", key: "category", width: 22 },
    { header: "Answered", key: "answered", width: 12 },
    { header: "Answer rate %", key: "answerRate", width: 14 },
    { header: "Likert average", key: "likert", width: 14 },
    { header: "Interpretation", key: "interpretation", width: 30 },
    { header: "Numeric average", key: "numeric", width: 16 },
  ];
  styleHeader(questions.getRow(1));
  for (const question of content.questions) {
    questions.addRow({
      code: question.code,
      text: question.text,
      type: question.type,
      category: question.category ?? "",
      answered: question.answered,
      answerRate: question.answerRate,
      likert: question.likertAverage ?? "",
      interpretation: question.likertInterpretation ?? "",
      numeric: question.numericAverage ?? "",
    });
  }

  const distributions = workbook.addWorksheet("Distributions");
  distributions.columns = [
    { header: "Question", key: "question", width: 50 },
    { header: "Option", key: "option", width: 28 },
    { header: "Count", key: "count", width: 10 },
    { header: "Percentage", key: "percentage", width: 12 },
  ];
  styleHeader(distributions.getRow(1));
  for (const question of content.questions) {
    for (const entry of question.distribution ?? []) {
      distributions.addRow({ question: `${question.code} ${question.text}`, option: entry.label, count: entry.value, percentage: entry.percentage });
    }
  }

  const sentiment = workbook.addWorksheet("Sentiment & Trend");
  sentiment.columns = [
    { header: "Sentiment", key: "label", width: 18 },
    { header: "Count", key: "count", width: 10 },
    { header: "Percentage", key: "percentage", width: 12 },
  ];
  styleHeader(sentiment.getRow(1));
  for (const entry of content.sentiment) sentiment.addRow({ label: entry.label, count: entry.value, percentage: entry.percentage });
  sentiment.addRow({});
  const trendHeader = sentiment.addRow(["Trend date", "Responses", "Completed"]);
  styleHeader(trendHeader);
  for (const point of content.trend) sentiment.addRow([point.date, point.responses, point.completed]);

  if (content.rawResponses.length) {
    const responses = workbook.addWorksheet("Responses");
    responses.columns = [
      { header: "Respondent", key: "respondent", width: 26 },
      { header: "Group", key: "group", width: 20 },
      { header: "Submitted", key: "submitted", width: 22 },
      { header: "Source", key: "source", width: 16 },
      { header: "Status", key: "status", width: 14 },
      { header: "Question", key: "question", width: 50 },
      { header: "Answer", key: "answer", width: 60 },
    ];
    styleHeader(responses.getRow(1));
    for (const response of content.rawResponses) {
      for (const answer of response.answers) {
        responses.addRow({
          respondent: response.respondent,
          group: response.group ?? "",
          submitted: formatWhen(response.submittedAt),
          source: response.source,
          status: response.status,
          question: `${answer.code} ${answer.question}`,
          answer: answer.answer,
        });
      }
    }
  }

  const insights = workbook.addWorksheet("AI Insights");
  insights.columns = [
    { header: "Type", key: "type", width: 20 },
    { header: "Value", key: "value", width: 90 },
  ];
  styleHeader(insights.getRow(1));
  insights.addRow({ type: "Summary", value: content.aiSummary });
  for (const keyword of content.keywords) insights.addRow({ type: "Keyword", value: `${keyword.keyword} (${keyword.count})` });
  for (const theme of content.themes) insights.addRow({ type: "Theme", value: `${theme.theme} (${theme.count})` });
  for (const item of content.painPoints) insights.addRow({ type: "Pain point", value: item });
  for (const item of content.suggestions) insights.addRow({ type: "Suggestion", value: item });
  for (const item of content.concerns) insights.addRow({ type: "Concern", value: item });

  const written = await workbook.xlsx.writeBuffer();
  return Buffer.from(written as ArrayBuffer);
}

